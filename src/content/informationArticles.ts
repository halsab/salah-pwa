export function methodologyArticle(): string {
  return `# Как рассчитывается время намаза

VaqtPro рассчитывает время намаза для выбранного местоположения на устройстве. Расписание доступно без подключения к интернету.

## Откуда берётся расписание

В автоматическом режиме приложение выбирает региональный расчётный профиль по подтверждённым сведениям о местоположении. Если подходящий региональный профиль не определён, используется профиль Muslim World League.

В Татарстане применяется расчётный профиль «Татарстан». Для других регионов используется соответствующий расчётный профиль или общий профиль по умолчанию.

## Как рассчитывается время

Расчёт выполняется непосредственно на устройстве с помощью библиотеки [Adhan JS](https://github.com/batoulapps/adhan-js). Подключение к интернету для самого расчёта не требуется.

Учитываются географические координаты, дата, часовой пояс, положение Солнца и выбранная методика.

- **Фаджр и Иша** определяются по положению Солнца относительно горизонта либо по временному интервалу, установленному методикой.
- **Зухр** для профиля «Татарстан» в некоторых населённых пунктах использует фиксированное местное время. В остальных местах он рассчитывается как 12:00 или через минуту после солнечного зенита — выбирается более позднее время.
- **Аср** рассчитывается по длине тени. Доступны ханафитский и стандартный методы.
- **Магриб** определяется по заходу Солнца с учётом параметров расчётного профиля.

Восход и зенит рассчитываются как отдельные астрономические события. Зенит не является временем Зухра.

## Методики расчёта

В разных странах и религиозных организациях применяются различные методики определения времени намаза.

VaqtPro поддерживает несколько расчётных профилей, включая Татарстан, Россию, Турцию, Всемирную мусульманскую лигу и другие региональные варианты.

В автоматическом режиме приложение подбирает профиль по доступным данным о местоположении. Если определить подходящий региональный профиль не удалось, используется методика Всемирной мусульманской лиги (MWL).

В настройках можно самостоятельно выбрать расчётный профиль, метод Асра и правило для северных широт.

Расчётные профили Татарстана и России — независимые методы расчёта в VaqtPro. Они не являются официальными расписаниями религиозных организаций и могут отличаться от местного расписания.

## Особенности северных широт

В северных регионах в определённые периоды года Солнце может не опускаться достаточно низко под горизонт. Из-за этого обычный расчёт Фаджра или Иша по сумеркам становится затруднительным.

Для таких случаев предусмотрены специальные правила расчёта.

В профиле «Татарстан», если астрономический угол определить надёжно нельзя:
- Фаджр определяется за 120 минут до восхода.
- Иша определяется через 90 минут после захода Солнца.

Другие методики могут использовать доли ночи или астрономические данные ближайшего подходящего дня либо местоположения.

Время, определённое с применением резервного правила, является расчётной оценкой и может отличаться от местного расписания.

## Местоположение и часовой пояс

При использовании GPS время рассчитывается по текущим координатам, а часовой пояс берётся из настроек устройства. Сами координаты не определяют часовой пояс автоматически.

При выборе города через поиск используется часовой пояс этого города из справочника GeoNames.

Расчёт выполняется по координатам выбранного местоположения. Для точного отображения расписания важно, чтобы местоположение и часовой пояс были определены правильно.

## Работа без интернета

Сам расчёт времени намаза работает без подключения к интернету.

Расчёт расписания и выбор сохранённых мест доступны без сети. Поиск новых городов может требовать подключения к интернету.

## Точность и ограничения

Расчётное время может отличаться от расписания местной мечети или религиозной организации. Причинами могут быть различия в методиках, правилах округления, местоположении и установленных временных поправках.

VaqtPro — информационное приложение и не является официальным представителем религиозных организаций.

Мы стремимся обеспечить корректность расчётов, но не можем гарантировать полное совпадение с местными расписаниями или отсутствие ошибок.

**Рекомендуем проверять время намаза по надёжным местным источникам**, особенно если используются расчётные методики или специальные правила для северных широт.`
}
